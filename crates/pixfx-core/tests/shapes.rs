#[test]
fn bolt_and_forks_match_pixelfx() {
    let mut r = Rng::new(4);
    let path = bolt(&mut r, 0.0, 0.0, 40.0, 60.0, 0.22, 5);
    assert_path(&path, &BOLT);
    let branches = forks(&mut r, &path, 3, 20.0, 0.3, 0.9);
    assert_eq!(branches.len(), FORKS.len());
    for (got, want) in branches.iter().zip(&FORKS) {
        assert_path(got, want);
    }
}

#[test]
fn bolt_of_a_zero_length_segment_stays_finite() {
    // JS `L || 1`: a zero-length segment divides by 1, not 0.
    let mut r = rng(&[1.0]);
    let path = bolt(&mut r, 5.0, 5.0, 5.0, 5.0, 0.22, 2);
    assert_eq!(path.len(), 5);
    assert!(path.iter().all(|p| p.0 == 5.0 && p.1 == 5.0));
}
