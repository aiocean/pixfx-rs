/// Paint the arms at moment `s`: `fold` of them a whole turn apart round the origin, the first turned
/// `quarters` quarter turns clockwise.
pub fn paint(p: &mut Painter, ramp: &[Rgba], s: f64, fold: u32, quarters: u32) {
    let turn = |k: &mut Knot| {
        for _ in 0..quarters % 4 {
            *k = (-k.1, k.0, k.2, k.3);
        }
    };
    let mut arm = pose(&ARM, s);
    arm.iter_mut().for_each(turn);
    let mut spike = pose(&SPIKE, s);
    spike.iter_mut().for_each(turn);
    let mut ink = Ink::new(fold).grain(0.3, 0.55, 15.0);
    ink.path(&arm);
    ink.path(&spike);
    // the shuriken flares (light on its own pixels only, nothing outside them)
    let flare = curve(&[(2.5, 0.0), (4.0, 1.0), (7.0, 0.5), (8.5, 0.0)], s);
    ink.paint(p, ramp, 32.0, 0.08 * (1.0 + 2.0 * flare));
}
